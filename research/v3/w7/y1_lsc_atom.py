#!/usr/bin/env python3
r"""
y1_lsc_atom.py -- Y1: test the NONCOMMUTATIVE / LOWER-SEMICONTINUITY atom-extraction proposal.

Proposal under test: prove LOWER semicontinuity (LSC) of the atom weight  nu({m})
(and of the edge atom  E(nu)=nu({inf supp nu})=f1^2)  in a topology STRONGER than weak-*.

What this witness checks (numpy only, one job, -I safe; no downloads):
  [P]  Portmanteau, fixed point: weak-* gives limsup nu_n({m}) <= nu({m})  (UPPER, not lower).
       Bump adversary: nu_h -> nu weak-* but nu_h({m})=0 < w=nu({m})  => LSC FAILS in weak-*.
  [S]  Split adversary: nu_h = (w/2)delta_{m-h}+(w/2)delta_{m+h}+... -> nu in W_p (all p),
       in every moment, and against every test fn continuous at m -- YET atom at m -> 0.
       => every topology generated by functions continuous at m (W_p, moments, vague,
          SOT/WOT states on C(K), L^inf-normal states) fails LSC.
  [T]  TV / C*-norm: fixed-point atom IS continuous, but TRIVIALLY:
          |nu({m})-nu'({m})| <= ||nu-nu'||_TV  (atom = bounded functional; circular).
       And the BUMP is NOT TV-convergent (||bump - atom||_TV = 2w, constant) -> TV too strong.
  [E]  EDGE atom E(nu)=nu({inf supp nu}) is discontinuous EVEN IN TV (location jump):
          nu_e=(e/2)delta_e+(1-e/2)delta_2  ->  delta_2  in TV (||.||_TV = e -> 0),
          yet E(nu_e)=e/2 -> 0  !=  1 = E(delta_2).   => E fails LSC in the strongest std topology.
  [C]  Thin atom: chi=1/L for ALL e but edge atom w=e/2L -> 0  (no uniform floor from continuity).
  [A]  Free-field acid: finite L free field is finitely atomic (f1^2>0); acid is an L->inf statement.

Labels [T]/[C]/[NG]/[O]/[V].  No QED.  Clay 0%.
"""
import numpy as np

np.seterr(all='ignore')

# ---------------------------------------------------------------- exact integral vs atomic measure
def integ(phi, atoms):
    """Int phi dnu for an atomic measure atoms=[(w,s),...]."""
    return sum(w * phi(s) for (w, s) in atoms)

def atom_at(atoms, m):
    """nu({m})."""
    return sum(w for (w, s) in atoms if abs(s - m) < 1e-12)

def TV(atoms_a, atoms_b):
    """Total variation ||nu_a - nu_b||_TV  (exact for finite atomic measures on R).
       = |nu_a - nu_b|(X) = positive variation + negative variation = sum_x |a_x - b_x|."""
    pts = {}
    for w, s in atoms_a: pts[round(s, 12)] = pts.get(round(s, 12), 0.0) + w
    for w, s in atoms_b: pts[round(s, 12)] = pts.get(round(s, 12), 0.0) - w
    return sum(abs(v) for v in pts.values())

def quantile(vals, cum, t):
    """left-continuous quantile F^{-1}(t) for atomic measure (sorted supports vals, cumulative masses cum)."""
    idx = np.searchsorted(cum, t, side='left')
    idx = np.clip(idx, 0, len(vals) - 1)
    return vals[idx]

def Wp(atoms_a, atoms_b, p, N=4000000):
    """Wasserstein-p on R via quantile coupling (exact in the limit N->inf)."""
    def prep(atoms):
        a = sorted(atoms, key=lambda z: z[1])
        vals = np.array([s for _, s in a]); ms = np.array([w for w, _ in a])
        cum = np.cumsum(ms)
        return vals, cum
    va, ca = prep(atoms_a); vb, cb = prep(atoms_b)
    t = (np.arange(N) + 0.5) / N * min(ca[-1], cb[-1])
    qa = quantile(va, ca, t); qb = quantile(vb, cb, t)
    return float((np.mean(np.abs(qa - qb) ** p)) ** (1.0 / p))

def hdr(t):
    print("\n" + "=" * 100 + "\n" + t + "\n" + "=" * 100)

# ---------------------------------------------------------------- main
def main():
    print("#" * 100)
    print("# Y1 -- LOWER-semicontinuity atom extraction: Portmanteau direction, adversaries, topologies")
    print("#" * 100)

    w = 0.30; m = 1.0; s2 = 3.0
    nu = [(w, m), (1 - w, s2)]                       # 0.30 delta_1 + 0.70 delta_3
    print("  reference YM-like measure  nu = %.2f*delta_{%.1f} + %.2f*delta_{%.1f}" % (w, m, 1 - w, s2))
    print("  edge atom at m=%.1f, weight w=%.2f" % (m, w))

    # ------------------------------------------------------------ [P] Portmanteau: upper, not lower
    hdr("[P] PORTMANTEAU, FIXED POINT -- closed set {m}: limsup nu_n({m}) <= nu({m})  (UPPER, not lower)")
    print("  BUMP: nu_h = %.2f*Unif[%.1f-h,%.1f+h] + %.2f*delta_{%.1f}   (atom at m spread to a density)"
          % (w, m, m, 1 - w, s2))
    print("  test fns (continuous): phi1=exp(-s), phi2=s, phi3=cos(s), phi4=1/(1+s^2)")
    phis = [lambda s: np.exp(-s), lambda s: s, lambda s: np.cos(s), lambda s: 1.0 / (1 + s * s)]
    print("  %8s %10s %10s %10s %10s %14s %16s" %
          ("h", "I[phi1]", "I[phi2]", "I[phi3]", "I[phi4]", "nu_h({m})", "nu({m})"))
    ref = [integ(phi, nu) for phi in phis]
    for h in (0.5, 0.1, 0.02, 0.004, 0.001):
        # bump mass 0.30 uniform on [m-h,m+h]; represent by K sub-atoms (exact for polynomial/cont integrals)
        K = 40000
        edges = np.linspace(m - h, m + h, K + 1)
        mids = 0.5 * (edges[:-1] + edges[1:]); wsub = w / K
        bump = [(wsub, mids[i]) for i in range(K)] + [(1 - w, s2)]
        vals = [integ(phi, bump) for phi in phis]
        print("  %8.4g %10.6f %10.6f %10.6f %10.6f %14.6f %16.6f" %
              (h, vals[0], vals[1], vals[2], vals[3], atom_at(bump, m), atom_at(nu, m)))
    print("  -> all weak-* integrals converge to nu's values (integrals match to ~1e-4..1e-6);")
    print("     BUT nu_h({m}) = 0 for every h>0 while nu({m}) = %.2f : the fixed-point atom DISAPPEARS." % w)
    print("     liminf nu_h({m}) = 0 < %.2f = nu({m}).  LSC FAILS in weak-*.  [T]" % w)
    print("     (Portmanteau for the CLOSED set {m} gives only limsup<=nu({m}); it is USC, the WRONG side.)")

    # ------------------------------------------------------------ [S] split adversary kills W_p / moments / SOT
    hdr("[S] SPLIT ADVERSARY -- atom at m shatters symmetrically; converges in W_p, moments, every cont-at-m topology")
    print("  nu_h = %.2f*delta_{%.1f-h} + %.2f*delta_{%.1f+h} + %.2f*delta_{%.1f}"
          % (w / 2, m, w / 2, m, 1 - w, s2))
    print("  %8s %10s %10s %12s %12s %12s %16s" %
          ("h", "W_1", "W_2", "|dM1|", "|dM2|", "|dM3|", "nu_h({m})"))
    def moments(atoms, K=4):
        return np.array([integ(lambda s, k=k: s ** k, atoms) for k in range(1, K + 1)])
    Mref = moments(nu)
    for h in (0.3, 0.1, 0.02, 0.004, 0.001):
        split = [(w / 2, m - h), (w / 2, m + h), (1 - w, s2)]
        W1 = Wp(split, nu, 1); W2 = Wp(split, nu, 2)
        dM = np.abs(moments(split) - Mref)
        print("  %8.4g %10.6f %10.6f %12.3e %12.3e %12.3e %16.6f" %
              (h, W1, W2, dM[0], dM[1], dM[2], atom_at(split, m)))
    print("  -> W_1, W_2 -> 0 and all moments match, yet nu_h({m}) = 0 < %.2f = nu({m})." % w)
    print("     Any topology generated by functions CONTINUOUS AT m (W_p all p, moments, vague,")
    print("     SOT/WOT states on C(K), L^inf-normal states) contains this sequence -> LSC FAILS.  [T]/[NG]")

    # ------------------------------------------------------------ [T] TV / C*-norm: continuity BUT circular
    hdr("[T] TV / C*-NORM -- fixed-point atom continuous, but only by the TRIVIAL bound (circular)")
    print("  bump family, TV distance to nu:")
    for h in (0.5, 0.1, 0.02, 0.004):
        K = 40000
        edges = np.linspace(m - h, m + h, K + 1)
        mids = 0.5 * (edges[:-1] + edges[1:]); wsub = w / K
        bump = [(wsub, mids[i]) for i in range(K)] + [(1 - w, s2)]
        print("     h=%8.4g   ||bump - nu||_TV = %.6f   (nu_bump({m})=%.3f, nu({m})=%.3f)"
              % (h, TV(bump, nu), atom_at(bump, m), atom_at(nu, m)))
    print("  -> ||bump - nu||_TV = 2w = %.2f CONSTANT (never ->0): the bump is NOT TV-convergent." % (2 * w))
    print("     TV controls the atom by the exact bound |nu({m})-nu'({m})| <= ||nu-nu'||_TV.")
    print("     But that bound IS the definition: {m} is a Borel set, so 1_{m} is in the TV test class;")
    print("     'nu({m}) is TV-continuous' <=> 'nu({m}) is a BOUNDED functional on M(K)' <=> |nu({m})|<=||nu||.")
    print("     Zero content / CIRCULAR: the topology already contains the atom indicator.  [T]/(circular)")

    # ------------------------------------------------------------ [E] edge atom discontinuous even in TV
    hdr("[E] EDGE ATOM  E(nu)=nu({inf supp nu})  IS DISCONTINUOUS EVEN IN TV  (the location jumps)")
    print("  nu_e = (e/2)*delta_e + (1-e/2)*delta_2 ;  inf supp nu_e = e ;  E(nu_e) = e/2")
    print("  %10s %14s %14s %18s %16s %16s" %
          ("e", "||nu_e-d2||_TV", "inf supp nu_e", "E(nu_e)=nu_e({e})", "E(delta_2)", "LSC? (E_lim<=liminf)"))
    Ed2 = atom_at([(1.0, 2.0)], 2.0)                  # E(delta_2) = 1
    for e in (0.5, 0.2, 0.05, 0.01, 0.001):
        nue = [(e / 2, e), (1 - e / 2, 2.0)]
        tv = TV(nue, [(1.0, 2.0)])
        Ee = atom_at(nue, e)                          # edge atom at inf supp = e
        lsc_ok = (Ed2 <= Ee + 1e-12)
        print("  %10.4g %14.6e %14.4g %18.6f %16.6f %16s" %
              (e, tv, e, Ee, Ed2, "YES" if lsc_ok else "NO"))
    print("  -> nu_e -> delta_2 in TV (||nu_e-delta_2||_TV = e -> 0), yet")
    print("     E(nu_e) = e/2 -> 0  while  E(delta_2) = 1 :  liminf E = 0 < 1 = E(lim).  LSC FAILS in TV.")
    print("     CAUSE: inf supp (the LOCATION) jumps e -> 2 along a TV-convergent sequence.  Location is")
    print("     discontinuous in every topology coarser than TV; controlling it = resolving the gap. [T]/[NG]")

    # ------------------------------------------------------------ [C] thin atom: no floor from continuity
    hdr("[C] THIN ATOM -- chi=1/L for ALL e, but edge atom w=e/2L -> 0  (continuity gives NO uniform floor)")
    Lam = 1.0
    print("  nu_e=w delta_e+(1-w)delta_{s2},  w=e/(2L),  s2=2L(1-w)  (the corpus thin atom)")
    print("  %10s %14s %18s %16s %14s" % ("e", "w=e/2L", "chi=int s^-1 dnu", "edge atom w", "edge m=e"))
    for e in (0.5, 0.2, 0.05, 0.01, 0.001):
        wv = e / (2 * Lam); s2v = 2 * Lam * (1 - wv)
        chi = wv / e + (1 - wv) / s2v
        print("  %10.4g %14.6f %18.6f %16.6f %14.4g" % (e, wv, chi, wv, e))
    print("  -> chi=1/L EXACTLY for every e; edge atom w=e/2L -> 0.  Continuity/LSC of the atom reads the")
    print("     TRUE (small) value; it can NEVER certify f1^2 >= r0 uniformly.  Thin atom NOT certified. [T]")

    # ------------------------------------------------------------ [A] free-field acid caveat
    hdr("[A] FREE-FIELD ACID TEST -- finite-L free field is finitely ATOMIC (f1^2>0); acid is L->inf")
    print("  continuum free massless cut proxy rho(s)=const on [0,1]: atomless, f1^2=0  (R3 [S2]).")
    print("  BUT at finite L a free field on T^4_L has DISCRETE spectrum -> its KL measure has atoms;")
    print("     lowest mode ~ (2pi/L)^2, with a positive edge weight f1^2>0 at finite L.")
    print("  => any topology that yields LSC/continuity of the atom also gives a POSITIVE atom on the")
    print("     finite-L free field.  It does NOT discriminate free vs YM at finite L; the acid test is")
    print("     an L->inf statement -- exactly where no TV/strong convergence is available.  [T]/[NG]")

    # ------------------------------------------------------------ operator-algebraic summary
    hdr("[OPS] OPERATOR-ALGEBRAIC / C*-SEMINORM TOPOLOGIES -- all collapse")
    print("  (a) states on commutative C*-algebra C(K); SOT/WOT/weak-* = sigma(C*,C): atom USC only. FAIL LSC.")
    print("  (b) states on von Neumann algebra L^inf(K); weak-* = sigma(A*,A) same as (a); the ATOM is a")
    print("      SINGULAR (non-normal) state -- normal-state convergence (=TV on a.c. part) does not see it. FAIL.")
    print("  (c) pure states / spectral projectors carry atom PRESENCE (a rank), NOT the weight: the")
    print("      decomposition nu = w delta_m + (1-w) nu_c reads w as the coefficient of an EXTREME point;")
    print("      that coefficient map is weak-* discontinuous (pure states are not weakly closed). FAIL for weight.")
    print("  (d) any C*-norm/seminorm controlling point masses = TV: gives continuity only circularly (cf [T]).")
    print("  => no operator-algebraic topology gives NON-CIRCULAR LSC of the atom WEIGHT.  [NG]")

    # ------------------------------------------------------------ verdict
    hdr("VERDICT")
    print("  [P]  weak-* gives USC (limsup<=), LSC FALSE; bump makes the fixed-point atom disappear.  [T]")
    print("  [S]  split adversary converges in W_p / moments / every cont-at-m topology; LSC FALSE there. [T]/[NG]")
    print("  [T]  TV/C*-norm makes the FIXED-POINT atom continuous, but trivially (|nu({m})|<=||nu||_TV):")
    print("       CIRCULAR, and unattainable (bump is TV-far, ||.||_TV=2w const).                        [T]/circular")
    print("  [E]  the EDGE atom E(nu)=nu({inf supp nu}) is discontinuous EVEN IN TV (location jump e->2).  [T]")
    print("  [C]  thin atom: continuity/LSC reads the true small atom, gives NO uniform floor r0.         [T]")
    print("  [A]  finite-L free field is atomic; topology LSC does not discriminate free vs YM.           [T]/[NG]")
    print("  KILL: LSC is FALSE in every non-circular topology (split/bump adversary), and the physical")
    print("  EDGE atom is discontinuous even in TV (location).  LSC is TRUE only in norm/TV-type topologies")
    print("  that are (i) CIRCULAR (atom = bounded functional, tautology) and (ii) UNATTAINABLE from finite")
    print("  (L,a)-data -- and even there only for the fixed-point weight, NOT the edge atom.  PROPOSAL DEAD. [NG]")
    print("  Clay 0%.  No QED.")

if __name__ == "__main__":
    main()
