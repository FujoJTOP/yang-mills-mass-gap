# Z = int_0^pi sin^2 u / u^2 du  (= Cin(2pi)/2),  NS = 1/4 (IBP, q11),  S = NS/Z
def Cin(x, K=80):                    # Cin(x) = sum_{k>=1} (-1)^{k+1} x^{2k}/((2k)!(2k))
    return sum((-1) ** (k + 1) * x ** (2 * k) / (math.factorial(2 * k) * 2 * k)
               for k in range(1, K + 1))


Z = Cin(2 * math.pi) / 2             # q11: Z = Cin(2pi)/2  (锚 1.218826696528612205905)
Cin2pi_2 = 1.218826696528612205905
S = 0.25 / Z
Varg = 0.0110592937729735899114          # q11_cert.log 锚 (beta-free)
D = 2.5**2 * Varg
Gpp1 = S - D
