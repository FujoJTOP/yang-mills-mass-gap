# t03_toy_models.py -- T03: 在可解模型上检验  G''(0) > 0  =>  m > 0   (找反例)
#
# 定义（全文统一，两处都与语料对齐）:
#   G''(0) := -d^2/da^2 log rho(a) |_{a=0},  rho = 粗变量 a 在该模型自身测度下的边缘分布
#            (0 维积分: rho ∝ e^{-S}; 0+1 维: rho = |psi_0|^2, 即欧氏路径积分单时刻边缘;
#             这一条使 q11 的 E[H+Phi''] - Var(G+Phi') 与 p09 的 S''(0) 落在同一对象上)
#   m      := inf( spec(H) \ {E_0} ) - E_0 ,  只在模型有 transfer 方向时定义; 0 维模型 => 无定义
#
# numpy-only, 确定性 (求积 / 三对角精确对角化), 无采样.

import math
import numpy as np

LOG = []


def P(s=""):
    print(s)
    LOG.append(s)


# ---------------------------------------------------------------- 0+1 谱: 三对角对角化
def spec(V, amin, amax, N):
    """H = p^2/2 + V(a), Dirichlet 盒; 返回 (E, psi) 最低两个."""
    a = np.linspace(amin, amax, N)
    h = a[1] - a[0]
    d = 1.0 / h**2 + V(a)
    e = np.full(N - 1, -0.5 / h**2)
    import scipy.linalg as sla
    E, U = sla.eigh_tridiagonal(d, e, select="i", select_range=(0, 2))  # 精确三对角
    return a, E, U


def gpp_from_psi(a, psi):
    """G''(0) = -d^2 log rho,  rho = psi^2; 在 a=0 处用中心差分 (网格含 0)."""
    i0 = int(np.argmin(np.abs(a)))
    assert abs(a[i0]) < 1e-12
    h = a[1] - a[0]
    f = np.log(psi**2)
    return -(f[i0 + 1] - 2 * f[i0] + f[i0 - 1]) / h**2


