P(f"Z(Cin(2pi)/2)      = {Cin2pi_2:.18f}      (q11 锚)")
P(f"S = NS/Z           = {S:.18f}       (q11: 0.20511529712307314798)")
P(f"D = beta^2 Var g   = {D:.18f}       (q11: 0.06912058608108493695)")
