# -*- coding: utf-8 -*-
"""
p5_r0.py — P3 振幅地板 r0 的四个问题（≤25min 总攻 P3）

Q1  a0=(2N)^{-2} 是哪两个因子？        (2N)^{-1} × (2N)^{-1}  ← 两个插入各带一次算子归一
Q2  r0 的"大小"重要吗？窗边依赖它吗？   ← 第一问
Q3  r0 与 (E-I2) 的 c 有关吗？          c = r0·λ（乘法桥）
Q4  改进 r0 有用吗？

约定（逐字出处）：
  O(x) = Σ_p (2N)^{-1} Re tr U_p                 P3-DRESSED-MASS:25
  u = c_f(β)/N = β/(2N²)                          BETA-CONVENTION:64（SU(2)⇒u=β/8）
  ū = ē·u,  ē = eΔC̄ = 54.3656                    X01:95-98, Z12:124
  r0 = ½ a0 (1−O(u))，a0 = (2N)^{-2} s，s=1        Z01:203-204, Z04 §2.3
  inf_L f₁² ≥ ¼(2N)^{-2}                          Z01:204
  m₁² ≥ f₁²/χ ≥ r0·λ                              Q6 (1.3), L2A:112, S14:109
"""
from fractions import Fraction as F

EDEL = 54.3656          # ē = e·Δ·C̄  (X01:95-98)
N = 2                   # SU(2)
TWO_N = 2 * N

def u_of(beta, n=N):
    return beta / (2 * n * n)

def ubar(beta, edel=EDEL, n=N):
    return edel * u_of(beta, n)

def r0(beta, a0, edel=EDEL, c_scale=F(1)):
    """r0 = ½ a0 (1 − ū) ；c_scale 用来测试"改进 a0 的常数"是否动窗"""
    a0 = F(a0) * c_scale
    return float(a0) / 2.0 * (1.0 - ubar(beta, edel))

def beta_HI(edel=EDEL, half=1.0, n=N):
    """ū ≤ half 的根 ⇒ β = half·(2N²)/ē"""
    return half * (2 * n * n) / edel

def hdr(t):
    print("\n" + "=" * 78)
    print(t)
    print("=" * 78)

# ─────────────────────────────────────────────────────────────────────────────
hdr("§1  a0 = (2N)^{-2}：两个因子，逐字算术（精确有理数）")
a0 = F(1, TWO_N ** 2)
M0 = F(1, 2 * N * N)                      # W3-SMALL-VOLUME:192  M0=Var((1/N)Re tr U)
s  = F(1)                                 # Z04 §2.3：dim Hom(1, f⊗f̄)=1 ⇒ s=1
print(f"N={N}  2N={TWO_N}   a0=(2N)^-2 = {a0} = {float(a0):.6f}")
print(f"  因子1 = 因子2 = (2N)^-1 = {F(1,TWO_N)} = {float(F(1,TWO_N)):.6f}   (每个插入的算子归一)")
print(f"  s=1 ⇒ a0 = 1/(4N²) = {a0}      [T]  Z04:71")
print(f"  ½a0   = {F(1,2)*a0} = {float(F(1,2)*a0):.6f}      ← 用户给的 r0≈1/32")
print(f"  ¼a0   = {F(1,4)*a0} = {float(F(1,4)*a0):.6f}      ← inf_L 地板 Z01:204")
print(f"  M0 = 1/(2N²) = {M0} = {float(M0):.6f}")
print(f"  原子权重分数 w1 = a0/M0 = {a0/M0}   (= s/2, W3:192)  ⇒ f₁²≤M0 允许的最大 s = {2*s}")
print("  ⇒ a0 的改善空间：s 只能取 1（被 dim Hom=1 钉死）；即使放开，w1≤1 也只允许 s≤2（×2）")

# ─────────────────────────────────────────────────────────────────────────────
hdr("§2  ★第一问：窗边依赖 r0 的『大小』吗？—— 不依赖，只依赖它的零点")
print("  窗边三个候选值，全部来自 (1−K·ū)=0 的根，与 a0 的常数无关：")
print(f"    K=1   (r0>0  ⟺ ū<1)          β = 8/ē  = {beta_HI():.6f}   (F05#13 的 0.147152)")
print(f"    K=1/2 (a0(1−Cu)≥½a0 ⟺ ū≤½)   β = 4/ē  = {beta_HI(half=0.5):.6f}   (M07/G05A 的 0.073576)")
print()
print("  把 r0 整体乘 C（= 改进 a0 的常数 / 改进 ½），窗边 β 逐位不变：")
print(f"  {'C':>10} {'r0(β=1/48)':>14} {'r0(β=1/12)':>14} {'β_edge(12 digits)':>20}")
for C in [F(1,1024), F(1,4), F(1), F(2), F(16), F(4096)]:
    b = beta_HI()
    print(f"  {str(C):>10} {r0(1/48, a0, c_scale=C):>14.8f} {r0(1/12, a0, c_scale=C):>14.8f} {b:>20.12f}")
print("  ⇒ β_edge 与 C 无关到 12 位；只有 r0 的值按 C 线性缩放。  [T]")

print("\n  r0(β) 的符号表（C=1）：窗边是 r0 的零点，不是 r0 的量级")
print(f"  {'β':>8} {'u':>10} {'ū':>10} {'1−ū':>10} {'r0':>14} {'sign':>6}")
for beta in [1/48, 0.05, 0.0736, 0.1, 1/12, 0.14715, 0.1472, 0.2, 0.5, 2.5]:
    ub = ubar(beta)
    rr = r0(beta, a0)
    sg = "+" if rr > 0 else ("0" if rr == 0 else "−")
    print(f"  {beta:>8.5f} {u_of(beta):>10.5f} {ub:>10.5f} {1-ub:>10.5f} {rr:>14.8f} {sg:>6}")

print("\n  ★ β=2.5：把 a0 放大 4096 倍也救不回符号（1−ū<0 与 a0 无关）：")
for C in [F(1), F(16), F(4096)]:
    print(f"    C={str(C):>5}  ū(2.5)={ubar(2.5):.4f}  1−ū={1-ubar(2.5):.4f}  r0(C·)={r0(2.5, a0, c_scale=C):>16.4f}")

# ─────────────────────────────────────────────────────────────────────────────
hdr("§3  r0 与 (E-I2) 的 c：c = r0·λ（乘法桥），线性、且 ∃c>0 对缩放不变")
print("  (T★)： (f₁²≥r0) ∧ (χ≤1/λ) ⇒ m₁² ≥ f₁²/χ ≥ r0·λ      Q6(1.3)/L2A:112/S14:109  [T given the pair]")
print(f"  {'C(r0 缩放)':>12} {'c=r0·λ (λ=1)':>16} {'c=r0·λ (λ=0.5)':>18} {'∃c>0?':>8}")
for C in [F(1), F(2), F(4), F(4096)]:
    base = r0(1/12, a0, c_scale=C)
    print(f"  {str(C):>12} {base:>16.8f} {base*0.5:>18.8f} {'是' if base > 0 else '否':>8}")
print("  ⇒ c 随 r0 线性；但 (E-I2) 只要求 ∃c>0 ⇒ 缩放 r0 不产生任何新内容。")
print("  ⇒ 承重的是 λ（H1 天花板），不是 r0 的常数。")
print("  ⇒ 且 r0 非 Z_O-不变（W95D:19 逐字：绝对值/地板 r0 随 Z_O² 重标 ⇒ 非不变量）；")
print("     可搬过 1/48→2.5 的只有比值 f₁²/χ、f₁²/M0。⇒ '改进 r0' 不是物理改进。")

# ─────────────────────────────────────────────────────────────────────────────
hdr("§4  (c) 符号/因子问题：½a0(1−O(u)) ≥ ½(2N)^{-2} 这一步")
print("  Z01:203 逐字链：  a0·D_∞ ≥ a0(1−Cu) ≥ ½a0 ≥ ½(2N)^{-2}")
print("  F05:65 的写法 ：  r0 = ½a0(1−O(u)) ≥ ½(2N)^{-2}      ← 这里 ½ 用了两次")
print()
print(f"  {'β':>9} {'ū':>9} {'1−Cu':>9} {'½a0(1−Cu) / ½(2N)^-2':>24} {'该步成立?':>10}")
for beta in [1/48, 0.05, 1/12, 0.14715]:
    Cu = ubar(beta)
    ratio = 1.0 - Cu
    print(f"  {beta:>9.5f} {Cu:>9.5f} {ratio:>9.5f} {ratio:>24.6f} {'是' if ratio >= 1 else '否':>10}")
print("  ⇒ 该步等价于 1−Cu ≥ 1 ⟺ Cu ≤ 0 ⟺ O(u)≤0。")
print("     DRESSED:16,170 把它写成 1±Cu（符号未定，Z04:14 逐字引用）⇒ 若取 1−Cu（u>0）则该步为假。")
print("     正确链只能靠 D_∞≥½（X02:111 的 ½×½），此时门槛是 ū≤½ ⟺ β≤4/ē=0.073576（不是 0.14715）。")
print(f"  数值：β=1/12 时 Cu=ū={ubar(1/12):.4f}，1−Cu={1-ubar(1/12):.4f} < 1 ⇒ F05:65 的那一步在此窗内为假。")

# ─────────────────────────────────────────────────────────────────────────────
hdr("§5  判（Q4：改进 r0 有用吗）")
b1, b2 = beta_HI(), beta_HI(half=0.5)
print(f"  (a) 改进 r0 对窗边：**无用**。窗边 = 零点，{b1:.6f}（符号）/ {b2:.6f}（≥½a0 步），")
print("      两者都由 ū 与常数 K 的比值定，a0 的常数整个约掉（C 扫描 12 位不变）。")
print("  (b) 唯一 r0 的『大小』进得去的地方：c = r0·λ（线性）。但那是 ∃c>0 的常数值，")
print("      不是窗边；且 r0 非 Z_O-不变 ⇒ 改良只是换归一，不是物理。")
print("  (c) 符号问题：成立（F05:65 的 ½ 双计 + 1±Cu 的符号未定）。")
print()
print("  数：a0=(2N)^-2=1/16=0.062500 ; ½a0=1/32=0.031250 ; ¼a0=1/64=0.015625 ; s=1 ; w1=1/2")
print(f"      β_edge(符号)={b1:.6f} ; β_edge(½a0 步)={b2:.6f} ; ū(2.5)={ubar(2.5):.4f}")
