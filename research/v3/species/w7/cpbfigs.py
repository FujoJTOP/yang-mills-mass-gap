"""CPB paper figures. Numbers quoted verbatim from GV1/GV2/GO3/GO1 (see captions for file:line)."""
import numpy as np, os
import matplotlib; matplotlib.use('Agg')
import matplotlib.pyplot as plt
OUT=r'D:\Dev\math\docs\figs\cpb'; os.makedirs(OUT,exist_ok=True)
n=np.arange(1,7)
R3 =np.array([1.0,0.69491525,0.75958328,0.77555285,0.78859390,0.79616959])
K3 =np.array([1.0,0.83361577,0.91241370,0.93843209,0.95360975,0.96272208])
D3 =np.array([0.0,0.305085,0.240417,0.224447,0.211406,0.203830])
P3 =np.array([0.0,0.212008,0.182617,0.174071,0.166714,0.162284])
R2 =np.array([np.nan,0.85185185,0.88333090,0.89421322,0.90035385,0.90408695])
K2 =np.array([np.nan,0.92295821,0.95949152,0.97243431,0.97922534,0.98333546])
B  =np.array([1,20,514,14748,450255,14305816],dtype=float)
# Fig1 kappa_c(n) vs criteria
fig,ax=plt.subplots(figsize=(7.4,4.6))
ax.plot(n,K3,'o-',color='navy',label=r'$\kappa_c(n)$  SU(3), $u=\beta/9$')
ax.plot(n,K2,'s-',color='teal',label=r'$\kappa_c(n)$  SU(2), $u=\beta/4$')
ax.axhline(0.81,c='crimson',ls='--',lw=1.6,label=r'$\kappa_c=0.81$: CPB-W and CPB-S both close')
ax.axhline(0.80,c='crimson',ls=':',lw=1.2,label=r'$\kappa_c=0.80$: CPB-S would survive')
nn=np.linspace(2,6,100); ax.plot(nn,(2/3)**(1/nn),'g-.',lw=1.3,label=r'forced by O3$\perp$CPB: $\kappa_c\geq(2/3)^{1/n}$')
ax.axhline(1.0,c='gray',ls=':',lw=1)
ax.set_xlabel('$n$ (number of surfaces / boundary size)'); ax.set_ylabel(r'$\kappa_c(n)$')
ax.set_title(r'$\kappa_c(n)\to 1$: the signed cancellation gives only $O(1)$, the count grows like $32^n$')
ax.set_ylim(0.6,1.06); ax.legend(fontsize=7.5,loc='lower right'); ax.grid(alpha=.3)
fig.tight_layout(); fig.savefig(os.path.join(OUT,'fig1_kappac.png'),dpi=150); plt.close(fig)
# Fig2 B_n growth
fig,(a1,a2)=plt.subplots(1,2,figsize=(11,4.2))
a1.semilogy(n,B,'o-',color='purple'); a1.set_xlabel('$n$'); a1.set_ylabel('$B_n$')
a1.set_title(r'cluster mass $B_n$: $1, 20, 514, 14748, 450255, 14305816$'); a1.grid(alpha=.3,which='both')
gr=np.array([B[i+1]/B[i] for i in range(5)])
a2.plot(n[1:],gr,'o-',color='darkorange'); a2.axhline(gr[-1],ls='--',c='gray')
a2.set_xlabel('$n$'); a2.set_ylabel('$B_n/B_{n-1}$')
a2.set_title(r'growth ratios $20.0,\,25.7,\,28.7,\,30.5,\,31.8$ — still rising'); a2.grid(alpha=.3)
a2.text(3.2,31.0,r'$B_n^{1/n}\geq 15.58$',fontsize=10,color='darkorange')
fig.tight_layout(); fig.savefig(os.path.join(OUT,'fig2_bn.png'),dpi=150); plt.close(fig)
# Fig3 O3 vacuity
fig,ax=plt.subplots(figsize=(7.2,4.5))
ax.semilogy(n[1:],D3[1:],'o-',color='crimson',label=r'$1-\rho(n)=1-|S_n|/Z_n$')
ax.semilogy(n[1:],1/R3[1:],'s--',color='navy',label=r'$\kappa_c^{n}=1/\rho(n)$')
ax.semilogy(n[1:],P3[1:],'^-',color='green',label=r'$(1-\rho)\kappa_c^{n}=\rho(1-\rho)\leq 1/4$')
ax.axhline(0.25,c='crimson',ls=':',lw=1.2,label='AM-GM bound 1/4')
ax.set_xlabel('$n$'); ax.set_ylabel('value (log)')
ax.set_title(r'O3 is vacuous: $(1-\rho)\kappa_c^n\leq1/4$ identically, decreasing in $n$ (SU(3))')
ax.legend(fontsize=8); ax.grid(alpha=.3,which='both')
fig.tight_layout(); fig.savefig(os.path.join(OUT,'fig3_o3.png'),dpi=150); plt.close(fig)
# Fig4 lambda_Ur sandwich
fig,ax=plt.subplots(figsize=(7.4,3.6))
ax.axvspan(15.5806,53.0007,color='navy',alpha=.25,label=r'rigorous sandwich $\lambda_{Ur}\in[15.58,\,53.00]$')
ax.plot([15.5806],[1],'o',color='navy'); ax.plot([53.0007],[1],'o',color='navy')
ax.plot([2.320251],[0],'s',color='teal',label=r'per-cluster lower bound $2.32$')
ax.axvline(1.6,c='crimson',ls='--',lw=1.6,label=r'criterion $\lambda_{Ur}<1/u=1.6$')
ax.set_yticks([0,1]); ax.set_yticklabels(['per cluster','shell mass']); ax.set_xscale('log')
ax.set_xlim(1.2,80); ax.set_xlabel(r'$\lambda_{Ur}$  (log scale)')
ax.set_title('ring 3 closed: both readings sit entirely above the criterion')
ax.legend(fontsize=8,loc='center right'); ax.grid(alpha=.3,axis='x',which='both')
fig.tight_layout(); fig.savefig(os.path.join(OUT,'fig4_lambdaur.png'),dpi=150); plt.close(fig)
print('figs ->',OUT)

