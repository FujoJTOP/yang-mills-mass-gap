"""w04_two_tube.py — Λ★ = 2m₁（两管/两胶球阈值）是否普遍？

判据对象：V05-I2TOY.md 的三个模型（1b 单 plaquette Laplace 塔 / 2D YM / N=∞ plaquette）。
本脚本只做三件事，全部精确算术（Fraction）：
  1. 量纲核查：Λ★ 与 m₁² 同量纲（Casimir 本征值 / s 轴），Λ★ 是 **质量平方**；
     逐模型给出 Λ★/2m₁ 与 Λ★/m₁²、Λ★/(2m₁)² 三个比，看哪个是纯数。
  2. 解 Λ★ = 2m₁ 的交叉点（g 或 N），判是否普遍。
  3. 判 I2 ⟺ m₁ < 2（(a) 读法）在格点单位下是否成立、是否是标度不变的判据。

不采样、无随机。py -3.12。
"""
from fractions import Fraction as F
import math

OUT = []


def p(s=""):
    OUT.append(str(s))


def c2f(N):
    """SU(N) 基础表示 C₂ = (N²−1)/(2N)"""
    return F(N * N - 1, 2 * N)


def c2adj(N):
    """SU(N≥3) 伴随 C₂ = N；SU(2): j=1 ⇒ C₂ = 2"""
    return F(2) if N == 2 else F(N)


def row(label, m1sq, Lstar, note=""):
    m1sq = F(m1sq) if not isinstance(m1sq, F) else m1sq
    Lstar = F(Lstar) if not isinstance(Lstar, F) else Lstar
    m1 = math.sqrt(m1sq)
    two = 2 * m1
    return dict(
        label=label,
        m1sq=m1sq, m1=m1, Lstar=Lstar, two_m1=two,
        L_over_m1sq=float(Lstar / m1sq),
        L_over_two_m1=float(Lstar) / two,          # 混合量纲：数值比只在格点单位有意义
        L_over_2m1sq=float(Lstar / (4 * m1sq)),    # 两管阈值写在 s 轴（质量²）上
        note=note,
    )


p("=" * 78)
p("W04 · 两管阈值 Λ★ = 2m₁ ? —— 三模型量纲核查（V05-I2TOY.md 数字，精确算术）")
p("=" * 78)
p()

# ── 模型 1b：单 plaquette 挂 Peter–Weyl 塔（SU(2)）
# C₂(j): 3/4, 2, 15/4, 6, 35/4（j=1/2,1,3/2,2,5/2）—— 严格递增、无聚点
p("[1b] 单 plaquette · Laplace/Peter–Weyl 塔（SU(2)）")
p("  C₂ 塔: j=1/2:3/4  1:2  3/2:15/4  2:6  5/2:35/4   层距: 5/4,7/4,9/4,11/4 (=j+1, 严格递增)")
r1 = row("1b plaquette-tower", F(3, 4), F(2), "Λ★=C₂(1)，质量²")
p(f"  m₁²={r1['m1sq']}  m₁={r1['m1']:.6f}  2m₁={r1['two_m1']:.6f}  Λ★={r1['Lstar']}")
p(f"  Λ★/m₁²={r1['L_over_m1sq']:.6f}   Λ★/(2m₁)={r1['L_over_two_m1']:.6f}   Λ★/(2m₁)²={r1['L_over_2m1sq']:.6f}")
p(f"  判：Λ★ > 2m₁ ? {r1['Lstar']} > {r1['two_m1']:.4f} = {r1['Lstar'] > r1['two_m1']}"
  f"  （差 {float(r1['Lstar']) - r1['two_m1']:.6f}；比 2/√3 = {2/math.sqrt(3):.6f}）")
p(f"  但 4m₁²=3 > Λ★=2 ⇒ 塔的最下层 rung 在**两胶球阈值之下**：Λ★/(2m₁)²={r1['L_over_2m1sq']:.4f} < 1")
p()

# ── 模型 2：2D YM（Migdal 精确）SU(2)：E_R=(g²/2)C₂(R)
# 2D 中 [g]=1（作用量 (1/g²)∫F²，[F]=2 ⇒ [g]=1）⇒ g² 是质量²
p("[2] 2D YM · SU(2)（Migdal 精确）E_R=(g²/2)C₂(R)")
p("  2D 量纲：[A_μ]=0? 用 E_R∝g²C₂ ⇒ [g²]=质量²，即 2D 里 [g]=1（与 4D 的 [g]=0 不同！）")
r2 = row("2D YM SU(2)", F(3, 8), F(1), "以 g² 为单位：m₁²=3g²/8, Λ★=g²")
p(f"  m₁²=3g²/8  m₁={math.sqrt(3/8):.6f}·g  2m₁={2*math.sqrt(3/8):.6f}·g  Λ★=g²")
p(f"  Λ★/m₁² = {r2['L_over_m1sq']:.6f}  （纯数 = C₂(adj)/C₂(f)=2/(3/4)）")
p(f"  Λ★/2m₁ = g²/(2g√(3/8)) = {1/(2*math.sqrt(3/8)):.6f}·g  —— 含一个 **长度/质量** 因子 ⇒ 非纯数")
p(f"  Λ★/(2m₁)² = {r2['L_over_2m1sq']:.6f} = C₂(adj)/(4C₂(f)) ⇒ 纯数，且 < 1")
# 解 Λ★ = 2m₁ ⇔ g² = 2g√(3/8) ⇔ g = 2√(3/8) = √(3/2)
g_star = 2 * math.sqrt(3 / 8)
p(f"  ⇒ Λ★=2m₁ 只在 g = 2√(3/8) = √(3/2) = {g_star:.6f}（即 g²=3/2）成立；g²→0 弱耦合时 Λ★/2m₁→0")
p(f"     验证：g²={g_star**2:.6f} vs 2g√(3/8)={2*g_star*math.sqrt(3/8):.6f}  （相等 → 只是单个耦合点）")
# SU(3)，同样 E_R=(g²/2)C₂(R)
N3 = 3
m1sq_3 = c2adj(N3) / 2      # = (1/2)·3 = 3/2 g²  —— 注意 m₁²=(g²/2)C₂(f)=2g²/3
m1sq_3 = c2f(N3) / 2        # = (g²/2)(4/3) = 2g²/3
L_3 = c2adj(N3) / 2         # Λ★ = (g²/2)C₂(adj) = 3g²/2
r3 = row("2D YM SU(3)", m1sq_3, L_3)
p(f"  SU(3)：m₁²=(g²/2)·{c2f(3)}={m1sq_3}g²={float(m1sq_3):.6f}g²  m₁={r3['m1']:.6f}g  2m₁={r3['two_m1']:.6f}g  Λ★={L_3}g²={float(L_3):.4f}g²")
p(f"    ρ²=Λ★/m₁² = {r3['L_over_m1sq']:.6f}（=C₂(adj)/C₂(f)=3/(4/3)=9/4）")
p(f"    Λ★/2m₁ = {r3['L_over_two_m1']:.6f}·g ⇒ 1.5g²=2g√(2/3) ⇔ g=2√(2/3)/1.5={r3['two_m1']/float(L_3):.6f}")
p(f"    Λ★/(2m₁)² = {r3['L_over_2m1sq']:.6f} = C₂(ad)/(4C₂(f)) = 9/16")
p()

# ── 模型 3：N=∞ 单 plaquette（Casimir 塔），Λ★ = 2m₁²
p("[3] N=∞ 单 plaquette · Casimir 塔：Λ★ = 2·m₁²  （**显式质量²**）")
p(f"  {'N':>6}{'m₁²':>12}{'m₁':>10}{'2m₁':>10}{'Λ★':>12}{'Λ★/m₁²':>9}{'Λ★/2m₁':>10}{'Λ★/(2m₁)²':>11}")
n_rows = []
for N in (2, 3, 4, 10, 100, 1000, 10 ** 5):
    m1sq = c2f(N)
    L = 2 * m1sq
    r = row(f"N={N}", m1sq, L)
    n_rows.append((N, r))
    p(f"  {N:>6}{float(m1sq):>12.6f}{r['m1']:>10.6f}{r['two_m1']:>10.6f}{float(L):>12.6f}"
      f"{r['L_over_m1sq']:>9.4f}{r['L_over_two_m1']:>10.4f}{r['L_over_2m1sq']:>11.4f}")
# Λ★=2m₁ ⇔ 2m₁²=2m₁ ⇔ m₁=1 ⇔ (N²−1)/(2N)=1 ⇔ N²−2N−1=0
N_star = 1 + math.sqrt(2)
p(f"  ⇒ Λ★=2m₁ ⇔ m₁=1 ⇔ (N²−1)/(2N)=1 ⇔ N²−2N−1=0 ⇔ N=1+√2={N_star:.6f} —— **非整数 N，无 SU(N) 命中**")
p(f"     检查：N=2 时 Λ★=1.5 < 2m₁={n_rows[0][1]['two_m1']:.4f}（Λ★ **小于** 2m₁）；N=3 时 Λ★={float(2*c2f(3)):.4f} > 2m₁={n_rows[1][1]['two_m1']:.4f}")
p(f"     N→∞：Λ★/2m₁ = m₁ = √((N²−1)/(2N)) → ∞，Λ★/(2m₁)² → 1/2（< 1）")
p()

# ── 汇总：不变量是哪个比
p("=" * 78)
p("汇总：三个比，只有一个与约定无关")
p("=" * 78)
p(f"  {'模型':<16}{'Λ★/m₁²':>10}{'Λ★/2m₁':>12}{'Λ★/(2m₁)²':>12}   备注")
p(f"  {'1b plaquette':<16}{r1['L_over_m1sq']:>10.4f}{r1['L_over_two_m1']:>12.4f}{r1['L_over_2m1sq']:>12.4f}   Casimir 纯塔，无割")
p(f"  {'2D YM SU(2)':<16}{r2['L_over_m1sq']:>10.4f}{'=0.8165·g':>12}{r2['L_over_2m1sq']:>12.4f}   中间比含 g（有量纲）")
p(f"  {'2D YM SU(3)':<16}{r3['L_over_m1sq']:>10.4f}{r3['L_over_two_m1']:>12.4f}{r3['L_over_2m1sq']:>12.4f}   ρ²=9/4；中间比含 g")
for N, r in n_rows[1:4]:
    p(f"  {'N=∞ (N=' + str(N) + ')':<16}{r['L_over_m1sq']:>10.4f}{r['L_over_two_m1']:>12.4f}{r['L_over_2m1sq']:>12.4f}   Λ★=2m₁² 显式质量²")
p("  ⇒ Λ★/m₁² ∈ {2, 8/3, 9/4} 皆 > 1（I2 真，margin ρ²=Λ★/m₁²）；Λ★/(2m₁)² ∈ [1/2,2/3] 皆 < 1")
p("  ⇒ **Λ★/2m₁ 不是纯数（2D 里带一个 g 的幂），不是可与 1 比较的不变量**")
p()

# ── (a) 读法：把 2m₁ 塞进质量² 的槽位 ⇒ I2 ⟺ m₁ < 2
p("=" * 78)
p("(a) 读法核查：Λ★ ≈ 2m₁ ⇒ I2 ⟺ 2m₁ > m₁² ⇔ m₁ < 2 ⇔ m₁² < 4（格点单位 a=1）")
p("=" * 78)
p("  这需要两个前提：(i) 把『质量』2m₁ 直接塞进『质量²』的槽位（量纲错配，只在 a=1 时有数值意义）；")
p("                    (ii) 断言 Λ★ **等于** 2m₁（待判命题，不能当输入）。")
p(f"  逐模型：1b m₁={r1['m1']:.4f}<2 ✓ I2 真；2D SU(2) m₁=0.6124g<2 ⇔ g<3.266；N=∞ N=3 m₁={n_rows[1][1]['m1']:.4f}<2 ✓")
p("  ⇒ 三模型都在 m₁<2 内，故『m₁<2 判据』与三行一致 —— 但它**不是标度不变判据**：")
p("     2D 里 m₁=g√(3/8)，g 是格点偶合（a 依赖）；把 a 显式写回：m₁a = g_lat√(3/8)，Λ★/2m₁ = a·g_lat·0.8165。")
p("     格点越细（a→0，物理 m_g 固定 ⇒ m_g a→0）⇒ m₁a<2 **自动成立** ⇒ 该判据在连续极限里恒真（空洞化）。")
p("  ⇒ 『I2 ⟺ m₁<2』是**格点单位的数值条件**，不是 I2 的内容；I2 的内容是『原子之上不立刻接割』。")
p()

# ── 两胶球阈值写在 s 轴（质量²）：4m₁²
p("=" * 78)
p("物理阈值：0⁺⁺ 两胶球阈值是 **能量** 2m_g ⇒ 写在 s=m² 轴上是 (2m_g)² = 4m_g²")
p("=" * 78)
p(f"  1b: (2m₁)²=4·3/4=3  vs Λ★=2   ⇒ Λ★/(2m₁)²={r1['L_over_2m1sq']:.4f}（Λ★ 在阈值**之下** 1）")
p(f"  2D: (2m₁)²=4·3g²/8=3g²/2 vs Λ★=g² ⇒ 比={r2['L_over_2m1sq']:.4f}（=C₂(ad)/4C₂(f)，与 g 无关）")
p(f"  N=∞: (2m₁)²=4m₁² vs Λ★=2m₁² ⇒ 比=1/2（与 N 无关）")
p("  ⇒ 三个模型里 Λ★ 都 **严格小于** 两胶球阈值（比 0.5 ~ 0.67 < 1）：隙是**单层 Casimir rung**，不是两粒子阈值。")
p("  ⇒ 若把 Λ★ 认成两胶球阈值，则 I2 ⟺ 4m₁²>m₁² 恒真（空洞）—— 与 V05 的 M6/4′/X 反例面矛盾 ⇒ 阈值不是 I2 的机制。")
p()

# ── 读法敏感度：阈值比较在两种坐标下**翻转**
p("=" * 78)
p("阈值比较的读法敏感度：s=m² 槽 vs 严格 s=E²（Källén–Lehmann 标准）")
p("=" * 78)
